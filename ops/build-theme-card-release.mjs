import fs from 'node:fs';
// 10.31-THEME.1 = deployed 10.29-BANNER.1 with the updated shared theme engine
// (cardAlpha). Same splice as ops/build-banner-release.mjs; nothing else changes.
const baseline=fs.readFileSync('ops/edge-release/party-api-10.29-BANNER.1.js','utf8');
const engine=fs.readFileSync('src/theme-engine.js','utf8').replace(/^export /gm,'');
const start=baseline.indexOf('const THEME_VERSION=1;'),end=baseline.indexOf('const THEME_STREAMER_FEATURES =');
const from=engine.indexOf('const THEME_VERSION=1;');
if(start<0||end<start||from<0)throw Error('Missing theme boundaries');
let result=baseline.slice(0,start)+engine.slice(from).trimEnd()+'\n'+baseline.slice(end);
if(result.split('version: "10.29-BANNER.1", themeBannerColors: 1,').length!==2)throw Error('Missing release marker');
result=result.replace('version: "10.29-BANNER.1", themeBannerColors: 1,','version: "10.31-THEME.1", themeBannerColors: 1, themeCardAlpha: 1,');
result=result.replace(/^\/\/ PA Party 10\.29-BANNER\.1:[^\n]*/,'// PA Party 10.31-THEME.1: production 10.29-BANNER.1 plus shared theme engine (card transparency); generated by ops/build-theme-card-release.mjs.');
fs.writeFileSync('ops/edge-release/party-api-10.31-THEME.1.js',result);
console.log('ok',result.length);
