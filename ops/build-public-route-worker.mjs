// Build the reviewed module Worker into one Dashboard-editor-compatible ES module.
// Tool dependencies live only in the isolated validation directory, not package.json.
import {createRequire} from 'node:module';
import {readFile,writeFile} from 'node:fs/promises';
import {createHash} from 'node:crypto';
import {fileURLToPath} from 'node:url';
import path from 'node:path';

const root=fileURLToPath(new URL('../',import.meta.url));
const require=createRequire(path.join(root,'.local-public-route-validation/worker-runtime/package.json'));
const esbuild=require('esbuild');
const output=path.join(root,'ops/public-route-worker.bundle.mjs');
const sha=value=>createHash('sha256').update(value).digest('hex');
const result=await esbuild.build({
 absWorkingDir:root,entryPoints:['ops/public-route-worker.mjs'],outfile:output,
 bundle:true,format:'esm',platform:'browser',target:'es2022',metafile:true,
 minify:false,sourcemap:false,legalComments:'eof',write:false,
 banner:{js:'// Generated by ops/build-public-route-worker.mjs. Cloudflare module Worker; no deployment performed.'}
});
const bytes=result.outputFiles.find(file=>file.path===output)?.contents;
if(!bytes)throw Error('Missing bundled Worker');
const text=new TextDecoder().decode(bytes);
if(/^\s*import\s/m.test(text))throw Error('Bundle still contains module imports');
if(/sb_secret_|service_role/.test(text.replace(/\/\/.*service_role.*$/gm,'')))throw Error('Unexpected private credential marker');
await writeFile(output,bytes);
const inputs={};
for(const relative of Object.keys(result.metafile.inputs).sort())inputs[relative.replaceAll('\\','/')]=sha(await readFile(path.join(root,relative.split(/[?#]/)[0])));
const metadata={schemaVersion:1,builder:'esbuild',builderVersion:esbuild.version,entry:'ops/public-route-worker.mjs',output:'ops/public-route-worker.bundle.mjs',bytes:bytes.byteLength,sha256:sha(bytes),inputs};
await writeFile(path.join(root,'ops/public-route-worker.bundle.json'),JSON.stringify(metadata,null,2)+'\n');
process.stdout.write(JSON.stringify({output:metadata.output,bytes:metadata.bytes,sha256:metadata.sha256,builderVersion:esbuild.version})+'\n');
