import fs from 'node:fs';
// Preserve the exact deployed JavaScript outside the shared theme engine.
// The previous production artifact includes the required TypeScript transpilation
// and web-push adapter; build-edge.mjs alone emits TypeScript.
const baseline=fs.readFileSync('ops/edge-release/party-api-10.29-SPACE.1.js','utf8');
const engine=fs.readFileSync('src/theme-engine.js','utf8').replace(/^export /gm,'');
const start=baseline.indexOf('const THEME_VERSION = 1;'),end=baseline.indexOf('const THEME_STREAMER_FEATURES =');
if(start<0||end<start)throw Error('Missing theme boundaries');
const result=(baseline.slice(0,start)+engine+'\n'+baseline.slice(end)).replace('version: "10.29-SPACE.1",','version: "10.29-BANNER.1", themeBannerColors: 1,');
fs.writeFileSync('ops/edge-release/party-api-10.29-BANNER.1.js',result.replace('// PA Party party-api release 10.29-SPACE.1 (generated by build-edge.mjs + bun transpile; do not edit).','// PA Party 10.29-BANNER.1: production SPACE.1 plus shared theme engine; generated by ops/build-banner-release.mjs.'));
